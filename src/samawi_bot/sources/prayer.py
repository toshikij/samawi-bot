"""Kemenag/MABIMS prayer times, ported from the app (spec §4, §5).

Same engine as `app/lib/features/prayer/domain/kemenag_prayer_calculator.dart`: adhan with
Subuh 20°, Isya 18°, Shafi'i Ashar, then a 2-minute ihtiyat applied so every window gets
narrower: starts move later and round up to the minute, Syuruq moves earlier and rounds down.
`tests/test_prayer.py` checks it minute-for-minute against output generated by the Dart engine.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import UTC, date, datetime, time, timedelta, timezone
from enum import Enum

import adhanpy.PrayerTimes as _adhan_pt
from adhanpy.calculation.CalculationParameters import CalculationParameters
from adhanpy.calculation.Madhab import Madhab
from adhanpy.PrayerTimes import PrayerTimes

from .snapshot import CITIES, Snapshot

IHTIYAT = timedelta(minutes=2)
FAJR_ANGLE = 20.0
ISHA_ANGLE = 18.0


class Prayer(Enum):
    SUBUH = "Subuh"
    SYURUQ = "Syuruq"
    DZUHUR = "Dzuhur"
    ASHAR = "Ashar"
    MAGHRIB = "Maghrib"
    ISYA = "Isya"

    @property
    def is_window_start(self) -> bool:
        return self is not Prayer.SYURUQ


class IndonesiaTZ(Enum):
    WIB = 7
    WITA = 8
    WIT = 9

    @property
    def tzinfo(self) -> timezone:
        return timezone(timedelta(hours=self.value), self.name)


@dataclass(frozen=True)
class City:
    name: str
    province: str
    latitude: float
    longitude: float
    tz: IndonesiaTZ


JAKARTA = City("Jakarta", "DKI Jakarta", -6.2088, 106.8456, IndonesiaTZ.WIB)

_CITY_RE = re.compile(
    r"IndonesianCity\(\s*name:\s*'([^']+)',\s*province:\s*'([^']+)',\s*latitude:\s*(-?[\d.]+),\s*"
    r"longitude:\s*(-?[\d.]+),\s*timeZone:\s*IndonesiaTimeZone\.(wib|wita|wit)"
)


def parse_cities(dart_source: str) -> list[City]:
    cities = [City(name, prov, float(lat), float(lon), IndonesiaTZ[tz.upper()]) for name, prov, lat, lon, tz in _CITY_RE.findall(dart_source)]
    if not any(c.name == "Jakarta" for c in cities):
        raise ValueError("indonesian_city.dart parsed without Jakarta; the parser no longer matches")
    return cities


def load_cities(snap: Snapshot) -> list[City]:
    return parse_cities(snap.read_text(CITIES))


def dart_rounded_minute(when: datetime) -> datetime:
    """`CalendarUtil.roundedMinute` from Dart adhan 2.0.0, which the app runs.

    adhanpy differs in two ways that move ~2% of times by a minute: Python's `round` is
    banker's rounding (30 s rounds down) where Dart rounds half away from zero, and adhanpy drops
    the seconds instead of carrying into the next hour at :59:30+. Dart also keeps the
    sub-second part (`copyWith(second: 0)`), so we do too.
    """
    carry = 1 if when.second >= 30 else 0
    return when.replace(second=0) + timedelta(minutes=carry)


# The app is the reference: match its rounding exactly (see tests/test_prayer.py).
_adhan_pt.rounded_minute = dart_rounded_minute


def _floor_minute(t: datetime) -> datetime:
    return t.replace(second=0, microsecond=0)


def _ceil_minute(t: datetime) -> datetime:
    floored = _floor_minute(t)
    return floored if floored == t else floored + timedelta(minutes=1)


def apply_ihtiyat(t: datetime, prayer: Prayer, ihtiyat: timedelta = IHTIYAT) -> datetime:
    if prayer.is_window_start:
        return _ceil_minute(t + ihtiyat)
    return _floor_minute(t - ihtiyat)


@dataclass(frozen=True)
class Schedule:
    city: City
    day: date
    times: dict[Prayer, datetime]  # UTC instants

    def local(self, prayer: Prayer) -> datetime:
        return self.times[prayer].astimezone(self.city.tz.tzinfo)

    def fmt(self, prayer: Prayer) -> str:
        return self.local(prayer).strftime("%H:%M")


def calculate(city: City, day: date) -> Schedule:
    params = CalculationParameters(fajr_angle=FAJR_ANGLE, isha_angle=ISHA_ANGLE)
    params.madhab = Madhab.SHAFI
    raw = PrayerTimes((city.latitude, city.longitude), day, calculation_parameters=params)
    by_name = {
        Prayer.SUBUH: raw.fajr,
        Prayer.SYURUQ: raw.sunrise,
        Prayer.DZUHUR: raw.dhuhr,
        Prayer.ASHAR: raw.asr,
        Prayer.MAGHRIB: raw.maghrib,
        Prayer.ISYA: raw.isha,
    }
    return Schedule(city, day, {p: apply_ihtiyat(t.astimezone(UTC), p) for p, t in by_name.items()})


def local_noon(day: date, tz: IndonesiaTZ = IndonesiaTZ.WIB) -> datetime:
    return datetime.combine(day, time(12), tz.tzinfo)


def minutes_between(a: datetime, b: datetime) -> int:
    return round((b - a).total_seconds() / 60)
